"""
Synthetic input workbook generator.

This module creates the Excel input file used by the model. The rest of the
stress-testing model should read the generated workbook, not call the synthetic
generation logic directly.

Workbook structure:
    banks      = combined balance sheet
    banks_amd  = AMD-only balance sheet, same columns as banks
    banks_fx   = FX-only balance sheet, same columns as banks

Later, the generated workbook can be replaced by a real banking input workbook
with the same sheet structure.
"""

from __future__ import annotations

from pathlib import Path
from typing import Dict

import numpy as np
import pandas as pd

from liquidity_stress.generation import (
    generate_armenian_public_reference_banks,
    assign_liquidity_metrics,
    recalibrate_ncof_to_target_lcr,
)
from liquidity_stress.config import LCR_ASSUMPTIONS


ASSET_COMPONENT_COLUMNS = [
    "cash_reserves",
    "loans",
    "total_securities",
    "interbank_assets",
    "government_securities",
    "bank_securities",
    "corporate_securities",
    "interest_earning_assets",
    "gross_advances_to_customers",
]

LIABILITY_COMPONENT_COLUMNS = [
    "deposits",
    "retail_deposits",
    "corporate_deposits",
    "other_deposits",
    "wholesale_funding",
    "interbank_liabilities",
]

EQUITY_LINKED_COLUMNS = [
    "equity",
    "charter_capital",
]


LIQUIDITY_LEVEL_COLUMNS = [
    "gross_30d_outflows",
    "recognized_30d_inflows",
    "capped_30d_inflows",
    "NCOF",
    "wholesale_funding_30d",
    "interbank_liabilities_30d",
]


class SyntheticBankingDataGenerator:
    """
    Generate a synthetic banking input workbook.

    Parameters
    ----------
    bank_reference:
        Public bank-level reference data.
    system_reference:
        Public system-level reference values.
    system_config:
        System-level model configuration.
    output_path:
        Excel path where the generated workbook will be saved.
    """

    def __init__(
        self,
        bank_reference: pd.DataFrame,
        system_reference: Dict,
        system_config: Dict,
        output_path: str | Path,
    ):
        self.bank_reference = bank_reference
        self.system_reference = system_reference
        self.system_config = system_config
        self.output_path = Path(output_path)

    def generate_banks(self) -> pd.DataFrame:
        """
        Generate the synthetic combined bank-level table.
        """
        return generate_armenian_public_reference_banks(
            bank_reference=self.bank_reference,
            system_reference=self.system_reference,
            system_config=self.system_config,
        )

    @staticmethod
    def _safe_share(numerator: pd.Series, denominator: pd.Series) -> pd.Series:
        return np.where(
            denominator.astype(float) > 0,
            numerator.astype(float) / denominator.astype(float),
            0.0,
        )

    @staticmethod
    def _enforce_additive_currency_liquidity_columns(
        combined: pd.DataFrame,
        banks_amd: pd.DataFrame,
        banks_fx: pd.DataFrame,
    ) -> tuple[pd.DataFrame, pd.DataFrame]:
        """
        Make synthetic AMD/FX liquidity-flow columns reconstruct the combined sheet.

        Why this is needed
        ------------------
        The synthetic currency sheets are generated by splitting balance-sheet
        stocks and then recomputing LCR components. The LCR inflow cap is
        nonlinear, so recomputed gross outflows, recognized inflows, and capped
        inflows need not add exactly back to the combined sheet even when NCOF
        does.

        For a synthetic input workbook, the cleanest convention is:
            1. keep balance-sheet stocks currency-specific,
            2. keep HQLA driven by the split asset stocks,
            3. allocate calibrated 30-day liquidity-flow columns across AMD/FX
               using each currency bucket's share of bank-level HQLA.

        This preserves:
            HQLA_combined = HQLA_AMD + HQLA_FX,
            NCOF_combined = NCOF_AMD + NCOF_FX,
            gross / recognized / capped flow additivity,
            LCR = HQLA / NCOF inside each sheet.

        Real-data workbooks should not rely on this helper; they should supply
        reported AMD/FX liquidity fields directly.
        """
        combined_indexed = combined.set_index("bank_id")

        out_amd = banks_amd.copy()
        out_fx = banks_fx.copy()

        amd_hqla = out_amd["HQLA"].astype(float)
        fx_hqla = out_fx["HQLA"].astype(float)
        total_split_hqla = amd_hqla + fx_hqla

        fallback_amd_share = pd.Series(
            SyntheticBankingDataGenerator._safe_share(
                out_amd["total_assets"],
                out_amd["total_assets"] + out_fx["total_assets"],
            ),
            index=out_amd.index,
        )

        amd_share = pd.Series(
            np.where(
                total_split_hqla > 0,
                amd_hqla / total_split_hqla,
                fallback_amd_share,
            ),
            index=out_amd.index,
        ).clip(lower=0.0, upper=1.0)

        fx_share = 1.0 - amd_share

        combined_by_row = combined_indexed.reindex(out_amd["bank_id"].astype(str))

        for column in LIQUIDITY_LEVEL_COLUMNS:
            if column not in combined_by_row.columns:
                continue

            combined_values = combined_by_row[column].astype(float).to_numpy()
            out_amd[column] = combined_values * amd_share.to_numpy()
            out_fx[column] = combined_values * fx_share.to_numpy()

        for out in [out_amd, out_fx]:
            out["LCR"] = np.where(
                out["NCOF"].astype(float) > 0,
                out["HQLA"].astype(float) / out["NCOF"].astype(float),
                np.nan,
            )
            out["HQLA_assets_ratio"] = np.where(
                out["total_assets"].astype(float) > 0,
                out["HQLA"].astype(float) / out["total_assets"].astype(float),
                0.0,
            )

        return out_amd, out_fx

    @staticmethod
    def _recompute_accounting_and_liquidity(sheet: pd.DataFrame) -> pd.DataFrame:
        """
        Recompute accounting aggregates and liquidity metrics for one sheet.
        """
        out = sheet.copy()

        for asset_column in [
            "government_securities",
            "bank_securities",
            "corporate_securities",
        ]:
            pledged_col = f"pledged_{asset_column}"
            if pledged_col not in out.columns:
                out[pledged_col] = 0.0

        if "cb_liquidity_funding" not in out.columns:
            out["cb_liquidity_funding"] = 0.0

        out["total_securities"] = (
            out["government_securities"]
            + out["bank_securities"]
            + out["corporate_securities"]
        )

        out["deposits"] = (
            out["retail_deposits"]
            + out["corporate_deposits"]
            + out["other_deposits"]
        )

        out["total_assets"] = (
            out["cash_reserves"]
            + out["loans"]
            + out["total_securities"]
            + out["interbank_assets"]
        )

        out["total_liabilities"] = (
            out["deposits"]
            + out["wholesale_funding"]
            + out["interbank_liabilities"]
        )

        out["equity"] = out["total_assets"] - out["total_liabilities"]

        liquidity_rows = []

        for _, row in out.iterrows():
            liquidity_metrics = assign_liquidity_metrics(
                total_assets=float(row["total_assets"]),
                cash_reserves=float(row["cash_reserves"]),
                government_securities=float(row["government_securities"]),
                bank_securities=float(row["bank_securities"]),
                corporate_securities=float(row["corporate_securities"]),
                retail_deposits=float(row["retail_deposits"]),
                corporate_deposits=float(row["corporate_deposits"]),
                other_deposits=float(row["other_deposits"]),
                wholesale_funding=float(row["wholesale_funding"]),
                interbank_liabilities=float(row["interbank_liabilities"]),
                loans=float(row["loans"]),
                interbank_assets=float(row["interbank_assets"]),
                lcr_assumptions=LCR_ASSUMPTIONS,
            )

            if "synthetic_target_LCR" in row.index and pd.notna(row["synthetic_target_LCR"]):
                liquidity_metrics = recalibrate_ncof_to_target_lcr(
                    liquidity_metrics=liquidity_metrics,
                    target_lcr=float(row["synthetic_target_LCR"]),
                )

            liquidity_rows.append(liquidity_metrics)

        liquidity = pd.DataFrame(liquidity_rows, index=out.index)

        for column in liquidity.columns:
            out[column] = liquidity[column]

        out["loans_assets_ratio"] = np.where(
            out["total_assets"] > 0,
            out["loans"] / out["total_assets"],
            0.0,
        )

        out["deposits_assets_ratio"] = np.where(
            out["total_assets"] > 0,
            out["deposits"] / out["total_assets"],
            0.0,
        )

        out["equity_assets_ratio"] = np.where(
            out["total_assets"] > 0,
            out["equity"] / out["total_assets"],
            0.0,
        )

        out["deposits_liabilities_ratio"] = np.where(
            out["total_liabilities"] > 0,
            out["deposits"] / out["total_liabilities"],
            0.0,
        )

        total_system_assets = float(out["total_assets"].sum())
        out["market_share"] = np.where(
            total_system_assets > 0,
            out["total_assets"] / total_system_assets,
            0.0,
        )

        return out

    def split_banks_by_currency(self, banks: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
        """
        Create AMD-only and FX-only sheets from the combined synthetic sheet.

        Important:
        This is only for synthetic/demo data. In real use, banks_amd and banks_fx
        should come directly from the provided real input workbook.
        """
        combined = banks.copy()

        fx_asset_share = pd.Series(
            self._safe_share(combined["FX_assets"], combined["total_assets"]),
            index=combined.index,
        )

        fx_liability_share = pd.Series(
            self._safe_share(combined["FX_liabilities"], combined["total_liabilities"]),
            index=combined.index,
        )

        amd_asset_share = 1.0 - fx_asset_share
        amd_liability_share = 1.0 - fx_liability_share

        banks_amd = combined.copy()
        banks_fx = combined.copy()

        banks_amd["currency"] = "AMD"
        banks_fx["currency"] = "FX"

        for column in ASSET_COMPONENT_COLUMNS:
            if column in combined.columns:
                banks_amd[column] = combined[column].astype(float) * amd_asset_share
                banks_fx[column] = combined[column].astype(float) * fx_asset_share

        for column in LIABILITY_COMPONENT_COLUMNS:
            if column in combined.columns:
                banks_amd[column] = combined[column].astype(float) * amd_liability_share
                banks_fx[column] = combined[column].astype(float) * fx_liability_share

        # Split capital-like reference fields proportionally by asset share.
        # These are not core stress-engine variables, but keeping them additive
        # makes the currency sheets internally consistent.
        for column in EQUITY_LINKED_COLUMNS:
            if column in combined.columns:
                banks_amd[column] = combined[column].astype(float) * amd_asset_share
                banks_fx[column] = combined[column].astype(float) * fx_asset_share

        # Recompute assets, liabilities, and equity from the split components.
        banks_amd = self._recompute_accounting_and_liquidity(banks_amd)
        banks_fx = self._recompute_accounting_and_liquidity(banks_fx)

        # The LCR inflow cap is nonlinear. After recomputing AMD/FX sheets,
        # enforce additivity for synthetic 30-day liquidity-flow columns so the
        # generated workbook passes currency reconstruction checks cleanly.
        banks_amd, banks_fx = self._enforce_additive_currency_liquidity_columns(
            combined=combined,
            banks_amd=banks_amd,
            banks_fx=banks_fx,
        )

        # Currency identity columns inside each sheet.
        banks_amd["AMD_assets"] = banks_amd["total_assets"]
        banks_amd["FX_assets"] = 0.0
        banks_amd["AMD_liabilities"] = banks_amd["total_liabilities"]
        banks_amd["FX_liabilities"] = 0.0
        banks_amd["FX_asset_share"] = 0.0
        banks_amd["FX_liability_share"] = 0.0

        banks_fx["AMD_assets"] = 0.0
        banks_fx["FX_assets"] = banks_fx["total_assets"]
        banks_fx["AMD_liabilities"] = 0.0
        banks_fx["FX_liabilities"] = banks_fx["total_liabilities"]
        banks_fx["FX_asset_share"] = 1.0
        banks_fx["FX_liability_share"] = 1.0

        for sheet in [banks_amd, banks_fx]:
            sheet["net_fx_gap"] = sheet["FX_assets"] - sheet["FX_liabilities"]
            sheet["net_fx_gap_assets_ratio"] = np.where(
                sheet["total_assets"] > 0,
                sheet["net_fx_gap"] / sheet["total_assets"],
                0.0,
            )

        return banks_amd, banks_fx

    def build_workbook_tables(self) -> dict[str, pd.DataFrame]:
        """
        Build all sheets required in the synthetic input workbook.
        """
        banks = self.generate_banks()
        banks_amd, banks_fx = self.split_banks_by_currency(banks)

        return {
            "banks": banks,
            "banks_amd": banks_amd,
            "banks_fx": banks_fx,
        }

    def export_excel(self) -> Path:
        """
        Export the synthetic banking input workbook.
        """
        self.output_path.parent.mkdir(parents=True, exist_ok=True)

        tables = self.build_workbook_tables()

        with pd.ExcelWriter(self.output_path, engine="openpyxl") as writer:
            for sheet_name, table in tables.items():
                table.to_excel(writer, sheet_name=sheet_name[:31], index=False)

        print(f"Synthetic banking input workbook saved to: {self.output_path}")
        print("Sheets written: banks, banks_amd, banks_fx")

        return self.output_path